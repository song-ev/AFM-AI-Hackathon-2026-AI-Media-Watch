# Phone country/area hints -> coordinates fallback.
COUNTRY_CENTROIDS = {
    "Казахстан": ("Казахстан", 48.0196, 66.9237),
    "Россия": ("Россия", 61.5240, 105.3188),
    "Кыргызстан": ("Кыргызстан", 41.2044, 74.7661),
    "Узбекистан": ("Узбекистан", 41.3775, 64.5853),
}


def lookup(name: str):
    """Return (label, region, country, lat, lon) for a place name, or None."""
    if not name:
        return None
    key = name.strip().lower()
    if key in _CITIES:
        return _CITIES[key]
    # Substring match: caption text like "сегодня снимаю в Алматы" -> алматы.
    for token, entry in _CITIES.items():
        if token in key or key in token:
            return entry
    return None


def scan_text(text: str):
    """Find the first known place mentioned anywhere in free text."""
    if not text:
        return None
    low = text.lower()
    # Longest tokens first so "усть-каменогорск" wins over partials.
    for token in sorted(_CITIES, key=len, reverse=True):
        if token in low:
            return _CITIES[token]
    return None


def country_fallback(country: str):
    """Coarse country centroid when only the country is known."""
    entry = COUNTRY_CENTROIDS.get(country)
    if entry:
        label, lat, lon = entry
        return (label, "", country, lat, lon)
    return None
