"""
Social-context screening: comment sentiment + bot/astroturf ("накрутка") analysis.

This is a fully offline analyzer (no LLM, no network): it distinguishes
template bot praise ("Спасибо, вывел 200к на Каспи!") from genuine human
reactions — both enthusiastic and skeptical ("это чистый скам, не ведитесь") —
and derives a *manipulation index* (степень накрутки) for the comment section.

Signals combined per comment:
  * scam-template match    — curated bot praise patterns (gratitude + payout);
  * money + gratitude      — a payout amount next to a thank-you;
  * emoji spam             — high emoji density, a classic bot tell;
  * duplicate / near-dup   — the same praise copy-pasted by many accounts;
  * bot-like username       — autogenerated handles (user1428573, ivan_9921);
  * sentiment              — lexicon-scored positive / negative / neutral.

A high share of bot-like *positive* comments together with real users shouting
"скам" is the textbook astroturf pattern around fraud videos — exactly what the
manipulation index captures. The account-follows watchlist check is preserved.
"""
from __future__ import annotations

import logging
import re

from ingestion.models import Video
from screening.models import ScreeningSignal

logger = logging.getLogger(__name__)

# --- Lexicons (lowercased; RU + some EN) -----------------------------------

# Genuine-skeptic markers: real people warning others. Their presence is a
# strong "this is fraud" signal AND evidence the praise above is astroturf.
SKEPTIC_TERMS = [
    "скам", "развод", "лохотрон", "лохотрóн", "мошенник", "мошенничество",
    "обман", "кидалово", "кидают", "не ведитесь", "не ведись", "разводилово",
    "не верьте", "не верь", "фейк", "афера", "пирамида", "наёбка", "наебка",
    "разводят", "украли", "не платят", "не выводят", "scam", "fraud", "fake",
    "ponzi", "развели", "верните деньги", "обманули", "жулик", "осторожно",
    "берегитесь", "не вздумайте", "потерял деньги", "слил деньги",
]

# Bot praise templates: gratitude + payout / "it works". Matched as regex so
# word order and amounts vary. These are the "Спасибо, выиграл миллион!" class.
BOT_TEMPLATE_PATTERNS = [
    r"спасибо.{0,30}(вывел|вывод|подн|выигра|занёс|занес|зашл|поднял)",
    r"(вывел|снял|поднял|выигра|занёс|занес).{0,20}(касп|карт|счёт|счет|kaspi)",
    r"реально\s+работает",
    r"проверен(о|а).{0,15}(работает|вывод|схем)",
    r"\+?\s*\d[\d\s.,]{2,}\s*(к|k|тыс|млн|000)?\s*(за\s+день|за\s+час|сегодня|вчера)",
    r"спасибо\s+за\s+(схем|сигнал|стратеги)",
    r"(благодар|спасиб).{0,20}(подн|вывел|выпла|работает)",
    r"кто\s+не\s+верит\s+зря",
    r"советую\s+всем.{0,20}(зайти|попроб|регистр)",
    r"уже\s+(вывел|поднял|выигра|снял)",
    r"легко\s+поднял",
    r"выплат(ил|или|а).{0,15}(момент|сразу|быстро)",
]

# Generic positive/hype lexicon (weaker; only meaningful in bulk).
POSITIVE_TERMS = [
    "спасибо", "топ", "работает", "реально", "проверено", "советую",
    "рекомендую", "лучший", "огонь", "красавчик", "благодарю", "выплатили",
    "занос", "поднял", "выигрыш", "профит", "лудовод", "thanks", "работаю",
]

# Money / payout mentions (amounts, currencies, slang).
_MONEY_RE = re.compile(
    r"(?:\+?\s*\d[\d\s.,]{2,}\s*(?:к|k|тыс|млн|млрд|000|₸|тг|руб|\$|€))"
    r"|(?:\d+\s*(?:касп|kaspi))",
    re.IGNORECASE,
)

# Emoji / pictographic ranges (rough but enough for density scoring).
_EMOJI_RE = re.compile(
    "[" "\U0001F000-\U0001FAFF" "\U00002600-\U000027BF" "\U0001F1E6-\U0001F1FF"
    "\U00002190-\U000021FF" "\U00002B00-\U00002BFF" "]",
    flags=re.UNICODE,
)

# Autogenerated / throwaway usernames: a name stem followed by a long digit run,
# or mostly-digit handles. e.g. user1428573, ivan_9921, id7740025513.
_BOT_USERNAME_RE = re.compile(r"^[a-zа-я._]*\d{4,}$|^id\d{6,}$|^user[._]?\d+$", re.IGNORECASE)

_WORD_RE = re.compile(r"[\w']+", re.UNICODE)
_NON_ALNUM_RE = re.compile(r"[^\w\s]", re.UNICODE)

MANIPULATION_TRIGGER = 0.45  # index above which the section looks astroturfed


def _normalize(text: str) -> str:
    """Lowercase, strip emoji/punctuation, collapse whitespace — for dedup."""
    t = _EMOJI_RE.sub(" ", text.lower())
    t = _NON_ALNUM_RE.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


def _emoji_density(text: str) -> float:
    if not text:
        return 0.0
    emojis = len(_EMOJI_RE.findall(text))
    chars = max(1, len(_NON_ALNUM_RE.sub("", text)))
    return emojis / (emojis + chars)


def _sentiment(text_low: str) -> str:
    pos = sum(1 for w in POSITIVE_TERMS if w in text_low)
    neg = sum(1 for w in SKEPTIC_TERMS if w in text_low)
    if neg > pos:
        return "negative"
    if pos > 0:
        return "positive"
    return "neutral"


def _classify_comment(author: str, text: str) -> dict:
    """Score one comment for bot-likelihood (0-1) with human-readable reasons."""
    low = text.lower()
    reasons: list[str] = []
    score = 0.0

    for pat in BOT_TEMPLATE_PATTERNS:
        if re.search(pat, low):
            score += 0.55
            reasons.append("шаблон бот-похвалы")
            break

    has_money = bool(_MONEY_RE.search(text))
    has_gratitude = any(g in low for g in ("спасибо", "благодар", "thanks"))
    if has_money and has_gratitude:
        score += 0.3
        reasons.append("сумма выплаты + благодарность")
    elif has_money and any(w in low for w in POSITIVE_TERMS):
        score += 0.15
        reasons.append("сумма выплаты + хайп")

    density = _emoji_density(text)
    if density >= 0.3 and len(low) < 60:
        score += 0.2
        reasons.append("эмодзи-спам")

    if author and _BOT_USERNAME_RE.match(author.strip()):
        score += 0.2
        reasons.append("автосгенерированный ник")

    sentiment = _sentiment(low)
    # A clearly skeptical comment is almost never a promo bot.
    if sentiment == "negative":
        score = min(score, 0.15)

    return {
        "author": author,
        "text": text,
        "score": round(min(1.0, score), 3),
        "is_bot": score >= 0.5,
        "sentiment": sentiment,
        "reasons": reasons,
    }


def _duplicate_clusters(normalized: list[str]) -> list[dict]:
    """Group comments whose normalized text is identical (copy-paste rings)."""
    buckets: dict[str, int] = {}
    for n in normalized:
        if len(n) < 6:  # ignore trivial "топ", "🔥"
            continue
        buckets[n] = buckets.get(n, 0) + 1
    return [
        {"text": text, "count": count}
        for text, count in sorted(buckets.items(), key=lambda kv: -kv[1])
        if count >= 2
    ]


def analyze_comment_section(comments) -> dict:
    """Pure function over an iterable of objects with `.author` / `.text`.

    Returned dict is the module's ``raw_output`` payload; also reused by the
    PDF dossier. Safe on an empty list.
    """
    classified = [_classify_comment(c.author or "", c.text or "") for c in comments]
    total = len(classified)
    if total == 0:
        return {
            "total_comments": 0, "bot_count": 0, "human_count": 0,
            "manipulation_index": 0.0, "sentiment": {"positive": 0, "negative": 0, "neutral": 0},
            "duplicate_clusters": [], "bot_comments": [], "skeptic_comments": [],
            "verdict": "Комментарии отсутствуют.",
        }

    bot = [c for c in classified if c["is_bot"]]
    skeptics = [c for c in classified if c["sentiment"] == "negative"]
    sentiment = {
        "positive": sum(1 for c in classified if c["sentiment"] == "positive"),
        "negative": len(skeptics),
        "neutral": sum(1 for c in classified if c["sentiment"] == "neutral"),
    }

    normalized = [_normalize(c["text"]) for c in classified]
    dup_clusters = _duplicate_clusters(normalized)
    duplicated_comments = sum(c["count"] for c in dup_clusters)

    bot_share = len(bot) / total
    dup_share = duplicated_comments / total
    # Skeptics shouting "скам" amid heavy praise raises the index further.
    skeptic_amid_praise = (
        0.15 if (skeptics and sentiment["positive"] >= 2 * max(1, len(skeptics))) else 0.0
    )
    manipulation_index = round(
        min(1.0, 0.6 * bot_share + 0.35 * dup_share + skeptic_amid_praise), 3
    )

    if manipulation_index >= 0.7:
        verdict = "Высокая накрутка: комментарии под видео массово фальсифицированы ботами."
    elif manipulation_index >= MANIPULATION_TRIGGER:
        verdict = "Признаки накрутки: значимая доля шаблонных бот-комментариев."
    elif skeptics:
        verdict = "Накрутки мало, но реальные пользователи предупреждают о мошенничестве."
    else:
        verdict = "Явных признаков накрутки не обнаружено."

    return {
        "total_comments": total,
        "bot_count": len(bot),
        "human_count": total - len(bot),
        "bot_share": round(bot_share, 3),
        "duplicate_share": round(dup_share, 3),
        "manipulation_index": manipulation_index,
        "sentiment": sentiment,
        "duplicate_clusters": dup_clusters[:8],
        "bot_comments": sorted(bot, key=lambda c: -c["score"])[:10],
        "skeptic_comments": [{"author": c["author"], "text": c["text"]} for c in skeptics][:8],
        "verdict": verdict,
    }


def analyze_social_context(video: Video) -> ScreeningSignal:
    """Comment sentiment / bot-накрутка analysis + watchlisted-follows check."""
    comments = list(video.comments.all()[:60])  # pinned + top comments
    analysis = analyze_comment_section(comments)

    is_triggered = False
    confidence = 0.0

    if analysis["manipulation_index"] >= MANIPULATION_TRIGGER:
        is_triggered = True
        confidence = max(confidence, 0.5 + 0.4 * analysis["manipulation_index"])
    # Even without astroturf, real users explicitly calling it a scam matters.
    if analysis["skeptic_comments"]:
        is_triggered = True
        confidence = max(confidence, 0.55)

    # Account-follows watchlist propagation (unchanged behaviour).
    watchlisted_follows: list[str] = []
    if video.social_account:
        suspicious_follows = video.social_account.follows.filter(is_watchlisted=True)
        for followed in suspicious_follows:
            watchlisted_follows.append(followed.username)
            is_triggered = True
            confidence = max(confidence, 0.9)
        if suspicious_follows.exists() and not video.social_account.is_watchlisted:
            video.social_account.is_watchlisted = True
            video.social_account.watchlist_reason = "Follows watchlisted accounts"
            video.social_account.save(
                update_fields=["is_watchlisted", "watchlist_reason"]
            )

    analysis["watchlisted_follows"] = watchlisted_follows

    return ScreeningSignal(
        module=ScreeningSignal.Module.SOCIAL_CONTEXT,
        is_triggered=is_triggered,
        confidence=round(min(1.0, confidence), 4),
        raw_output=analysis,
    )
